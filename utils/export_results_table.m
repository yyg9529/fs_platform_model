function T = export_results_table(results, outPath)
%EXPORT_RESULTS_TABLE 导出 V1.0.4 关键指标表。
% 功能说明:
%   从 results 提取姿态、气动、约束、筛选与 bump-adjusted 指标，生成 table/CSV。
%
% 输入:
%   results - run_case 输出结构体
%   outPath - 可选，CSV 输出路径
%
% 输出:
%   T - MATLAB table
%
% 关键物理假设:
%   converged/rulePass/designPass/feasible 分层输出；
%   bump-adjusted clearance 仅代表保守鲁棒性修正。
%
% 单位约定:
%   各指标单位见变量名后缀

vars = {
    'Converged', double(results.flags.converged); ...
    'RulePass', double(results.flags.rulePass); ...
    'DesignPass', double(results.flags.designPass); ...
    'Feasible', double(results.flags.feasible); ...
    'AeroPlatformPass', double(results.flags.aeroPlatformPass); ...
    'ScrapePassQuasiStatic', double(results.flags.scrapePassQuasiStatic); ...
    'ScrapePassBumpAdjusted', double(results.flags.scrapePassBumpAdjusted); ...
    'MapClassQuasiStatic', results.flags.mapClassQuasiStatic; ...
    'MapClassBumpAdjusted', results.flags.mapClassBumpAdjusted; ...
    'z_m', results.state.z; ...
    'theta_deg', results.state.theta_deg; ...
    'phi_deg', results.state.phi_deg; ...
    'hf_m', results.aero.hf; ...
    'hr_m', results.aero.hr; ...
    'hStaticMin_m', results.clearance.hStaticMin; ...
    'hDynamicMin_m', results.clearance.hDynamicMin; ...
    'hDynamicMinBumpAdjusted_m', results.clearance.hDynamicMinBumpAdjusted; ...
    'hMin_m', results.clearance.hMin; ...
    'EffectiveJounce_m', results.rules.minEffectiveJounce; ...
    'EffectiveDroop_m', results.rules.minEffectiveDroop; ...
    'EffectiveTotalTravel_m', results.rules.minEffectiveTotalTravel; ...
    'StaticGroundClearancePass', double(results.rules.staticGroundClearancePass); ...
    'DynamicClearancePass', double(results.targets.dynamicClearancePass); ...
    'DynamicClearanceBumpAdjustedPass', double(results.clearance.dynamicClearanceBumpAdjustedPass); ...
    'BumpAdjustedClearanceViolation', double(results.flags.bumpAdjustedClearanceViolation); ...
    'FzAero_N', results.aero.Fz; ...
    'Drag_N', results.aero.Drag; ...
    'FrontShare', results.aero.frontShare; ...
    'AeroLossPct', results.aero.lossPct; ...
    'FrontShareMigrationPct', results.aero.frontShareMigrationPct; ...
    'FzAxleFront_N', results.loads.FzAxleFront; ...
    'FzAxleRear_N', results.loads.FzAxleRear; ...
    'dF_LR_front_N', results.metrics.dF_LR_front; ...
    'dF_LR_rear_N', results.metrics.dF_LR_rear; ...
    'RollGradient_deg_per_g', results.metrics.rollGradient_deg_per_g; ...
    'PitchGradient_deg_per_g', results.metrics.pitchGradient_deg_per_g; ...
    'MaxWheelJounceUsagePct', results.metrics.maxWheelJounceUsagePct; ...
    'MaxWheelDroopUsagePct', results.metrics.maxWheelDroopUsagePct; ...
    'MaxShockCompUsagePct', results.metrics.maxShockCompUsagePct; ...
    'MaxShockReboundUsagePct', results.metrics.maxShockReboundUsagePct; ...
    'MinShockCompMargin_m', results.metrics.minShockCompMargin; ...
    'MinShockReboundMargin_m', results.metrics.minShockReboundMargin; ...
    'ShockStaticPositionPct', results.metrics.shockStaticPositionPct; ...
    'ShockBiasFromMidPct', results.metrics.shockBiasFromMidPct; ...
    'BumpReserveFront_m', results.metrics.bumpReserveFront; ...
    'BumpReserveRear_m', results.metrics.bumpReserveRear; ...
    'TireMode', encode_tire_mode(results.tire.mode); ...
    'TireComplianceIgnored', double(results.flags.tireComplianceIgnored); ...
    'MapClampedAny', double(results.flags.mapClampedAny); ...
    'InterpFallbackUsed', double(results.flags.interpFallbackUsed) ...
};

nameCol = vars(:, 1);
valCol = cell2mat(vars(:, 2));
T = table(nameCol, valCol, 'VariableNames', {'Metric', 'Value'});

if nargin >= 2 && ~isempty(outPath)
    writetable(T, outPath);
end
end

function v = encode_tire_mode(modeStr)
%ENCODE_TIRE_MODE 将 tire mode 编码为数值，便于导出统一表格。
s = lower(strtrim(char(string(modeStr))));
switch s
    case 'off'
        v = 0;
    case 'fixed'
        v = 1;
    case 'range'
        v = 2;
    otherwise
        v = -1;
end
end
