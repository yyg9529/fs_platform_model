function results = run_case(caseDef, options)
%RUN_CASE V1.5 单工况求解入口。
% 功能说明:
%   维持主接口不变，按固定流程执行：
%   validate_case_struct -> preprocess_case -> solve_equilibrium -> postprocess_results。
%   当 tire.mode='range' 时，自动计算 low/nominal/high 三场景并返回区间结果。
%
% 输入:
%   caseDef - 顶层输入结构体
%   options - 可选控制参数：
%             .solverOverrides (struct)
%             .exportCsv (char/string)
%             .returnOnError (logical)
%
% 输出:
%   results - 统一结果结构体（range 模式含 results.range）

if nargin < 2 || isempty(options)
    options = struct();
end

returnOnError = false;
if isfield(options, 'returnOnError')
    returnOnError = logical(options.returnOnError);
end

try
    % ===== 合并 solver 默认值与覆盖参数 =====
    solverDefault = default_solver_options();
    if ~isfield(caseDef, 'solver') || isempty(caseDef.solver)
        caseDef.solver = solverDefault;
    else
        [caseDef.solver, ~] = ensure_fields(caseDef.solver, solverDefault, true);
    end
    if isfield(options, 'solverOverrides') && isstruct(options.solverOverrides)
        fns = fieldnames(options.solverOverrides);
        for i = 1:numel(fns)
            caseDef.solver.(fns{i}) = options.solverOverrides.(fns{i});
        end
    end

    % ===== 输入校验 =====
    [caseDef, validation] = validate_case_struct(caseDef);
    caseDef.validation = validation;
    emit_validation_warnings(validation, caseDef.solver);
    if validation.badInput
        error('run_case:ValidationFailed', '%s', strjoin(validation.messages, ' | '));
    end

    if strcmpi(caseDef.tire.mode, 'range')
        results = run_tire_range_case(caseDef);
    else
        results = run_single_validated_case(caseDef);
    end

    % ===== 可选导出 =====
    if isfield(options, 'exportCsv') && ~isempty(options.exportCsv)
        export_results_table(results, options.exportCsv);
    end

catch ME
    if ~returnOnError
        rethrow(ME);
    end
    results = build_error_results(caseDef, ME);
end
end

function results = run_tire_range_case(caseDef)
%RUN_TIRE_RANGE_CASE 执行 tire.mode='range' 的 low/nominal/high 三场景求解。

rawRangeInputs = caseDef;
fRange = normalize_triplet(caseDef.tire.ktFrontRange);
rRange = normalize_triplet(caseDef.tire.ktRearRange);
labels = {'low', 'nominal', 'high'};

range = struct();
for i = 1:3
    caseI = caseDef;
    caseI.tire.mode = 'fixed';
    caseI.tire.ktFront = fRange(i);
    caseI.tire.ktRear = rRange(i);
    caseI.meta.name = sprintf('%s__kt_%s', caseDef.meta.name, labels{i});

    resI = run_single_validated_case(caseI);
    resI.tire.mode = 'range';
    resI.tire.ktCaseLabel = labels{i};
    range.(labels{i}) = resI;
end

% 主结果默认返回 nominal；若关闭该策略则返回 low 场景（保守筛选）。
if logical(caseDef.solver.rangeUseNominalAsPrimary)
    results = range.nominal;
    primaryLabel = 'nominal';
else
    results = range.low;
    primaryLabel = 'low';
end

results.meta.name = caseDef.meta.name;
results.meta.version = caseDef.meta.version;
results.inputsRaw = rawRangeInputs;
results.inputsNominal = range.nominal.inputs;

results.tire.mode = 'range';
results.tire.ktCaseLabel = primaryLabel;
results.tire.ktBand = [mean([fRange(1), rRange(1)]), mean([fRange(2), rRange(2)]), mean([fRange(3), rRange(3)])];

results.range = range;
results.range.labels = labels;
results.range.band = struct();
results.range.band.hMin = [range.low.clearance.hMin, range.nominal.clearance.hMin, range.high.clearance.hMin];
results.range.band.hStaticMin = [range.low.clearance.hStaticMin, range.nominal.clearance.hStaticMin, range.high.clearance.hStaticMin];
results.range.band.hDynamicMin = [range.low.clearance.hDynamicMin, range.nominal.clearance.hDynamicMin, range.high.clearance.hDynamicMin];
results.range.band.effectiveTotalTravel = [ ...
    range.low.rules.minEffectiveTotalTravel, ...
    range.nominal.rules.minEffectiveTotalTravel, ...
    range.high.rules.minEffectiveTotalTravel];
results.range.band.staticGroundClearancePass = [ ...
    range.low.rules.staticGroundClearancePass, ...
    range.nominal.rules.staticGroundClearancePass, ...
    range.high.rules.staticGroundClearancePass];
results.range.band.dynamicClearancePass = [ ...
    range.low.targets.dynamicClearancePass, ...
    range.nominal.targets.dynamicClearancePass, ...
    range.high.targets.dynamicClearancePass];
results.range.band.hDynamicMinBumpAdjusted = [ ...
    range.low.clearance.hDynamicMinBumpAdjusted, ...
    range.nominal.clearance.hDynamicMinBumpAdjusted, ...
    range.high.clearance.hDynamicMinBumpAdjusted];
results.range.band.dynamicClearanceBumpAdjustedPass = [ ...
    range.low.clearance.dynamicClearanceBumpAdjustedPass, ...
    range.nominal.clearance.dynamicClearanceBumpAdjustedPass, ...
    range.high.clearance.dynamicClearanceBumpAdjustedPass];
results.range.band.lossPct = [range.low.aero.lossPct, range.nominal.aero.lossPct, range.high.aero.lossPct];
results.range.band.frontShareMigrationPct = [range.low.aero.frontShareMigrationPct, ...
    range.nominal.aero.frontShareMigrationPct, range.high.aero.frontShareMigrationPct];
results.range.band.aeroPlatformPass = [ ...
    range.low.flags.aeroPlatformPass, range.nominal.flags.aeroPlatformPass, range.high.flags.aeroPlatformPass];
results.range.band.scrapePassQuasiStatic = [ ...
    range.low.flags.scrapePassQuasiStatic, range.nominal.flags.scrapePassQuasiStatic, range.high.flags.scrapePassQuasiStatic];
results.range.band.scrapePassBumpAdjusted = [ ...
    range.low.flags.scrapePassBumpAdjusted, range.nominal.flags.scrapePassBumpAdjusted, range.high.flags.scrapePassBumpAdjusted];
results.range.band.mapClassQuasiStatic = [ ...
    range.low.flags.mapClassQuasiStatic, range.nominal.flags.mapClassQuasiStatic, range.high.flags.mapClassQuasiStatic];
results.range.band.mapClassBumpAdjusted = [ ...
