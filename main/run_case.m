results.flags.feasibleRangeAll = all(results.range.band.feasible);
results.flags.feasibleRangeAny = any(results.range.band.feasible);
results.flags.rulePassRangeAll = all(results.range.band.rulePass);
results.flags.designPassRangeAll = all(results.range.band.designPass);
end

function results = run_single_validated_case(caseDef)
%RUN_SINGLE_VALIDATED_CASE 对“已通过 validate 的 caseDef”执行主求解流程。

rawInputs = caseDef;
caseDef = preprocess_case(caseDef);
solveOut = solve_equilibrium(caseDef);
results = postprocess_results(caseDef, solveOut);
results = apply_tire_force_layer(caseDef, results);
results.inputsRaw = rawInputs;
end

function results = apply_tire_force_layer(caseDef, results)
%APPLY_TIRE_FORCE_LAYER 在平台求解完成后追加 V1.5 轮胎代理后评估层。
% 关键说明:
%   1) 轮胎代理层严格位于 postprocess_results 之后，不回写主平衡链。
%   2) Fz 来自平台收敛后的 results.corners.FzWheel，而不是用户再次手填。
%   3) 若轮胎层失败，只置位 tireEvalFailed 并 warning，不清空平台主结果。

if ~isfield(caseDef, 'tire') || ~isfield(caseDef.tire, 'forceModel') ...
        || ~logical(caseDef.tire.forceModel.enable)
    return;
end

try
    tireTableData = load_tire_table_data(caseDef);
    tireOpNorm = normalize_tire_operating_points(caseDef, results, tireTableData);
    tireEval = evaluate_tire_table_model(caseDef, tireTableData, tireOpNorm);
    results = postprocess_tire_results(results, caseDef, tireTableData, tireOpNorm, tireEval);
catch ME
    results.flags.tireForceModelEnabled = true;
    results.flags.tireEvalFailed = true;
    results.tire.forceModel.enable = true;
    results.tire.forceModel.sourceType = lower(strtrim(char(string(caseDef.tire.forceModel.sourceType))));
    results.tire.forceModel.mode = lower(strtrim(char(string(caseDef.tire.forceModel.mode))));
    results.tire.forceModel.outOfRangePolicy = lower(strtrim(char(string(caseDef.tire.forceModel.outOfRangePolicy))));
    results.tire.forceModel.includeAligningMoment = logical(caseDef.tire.forceModel.includeAligningMoment);
    results.tire.validity.evalFailed = true;
    results.debug.tireForceModelError = ME.message;
    warning('run_case:TireEvaluationFailed', '%s', ME.message);
end
end

function emit_validation_warnings(validation, solver)
%EMIT_VALIDATION_WARNINGS 将 validation.warnings 以真实 warning 发出。

if ~isfield(solver, 'warnOnDeprecatedInput') || ~logical(solver.warnOnDeprecatedInput)
    return;
end
if ~isfield(validation, 'warnings') || isempty(validation.warnings)
    return;
end

for i = 1:numel(validation.warnings)
    warning('run_case:ValidationWarning', '%s', validation.warnings{i});
end
end

function trip = normalize_triplet(x)
if isempty(x) || ~isnumeric(x)
    error('run_case:BadTireRange', 'tire range must be numeric with 2 or 3 elements.');
end
x = sort(double(x(:)), 'ascend');
if numel(x) == 2
    trip = [x(1); 0.5 * (x(1) + x(2)); x(2)];
elseif numel(x) == 3
    trip = x;
else
    error('run_case:BadTireRangeSize', 'tire range must have 2 or 3 elements.');
end
if any(~isfinite(trip)) || any(trip <= 0)
    error('run_case:BadTireRangeValue', 'tire range values must be finite and positive.');
end
end

